"""Industry Compatible keymap data as static data (``ic_<major>_<minor>.py``).

Generated by tools/gen_ic_data.py from Blender's own
``$S\\presets\\keyconfig\\keymap_data\\industry_compatible_data.py`` (``generate_keymaps(Params())``) — one file
per Blender minor whose data differs; the newest file not newer than the running Blender is used. The add-on never
executes Blender's preset file itself (store review, GitHub #40).
``patch.KeyconfigData.remove`` still raises (5.2) or records ``patch.DRIFT`` (5.0 / 5.1) when an item we patch is
missing. Blender 4.5's data file is gone (the kit needs 5.0+).
"""

import copy
import sys
from importlib import import_module

from .. import compat

# Minors with a data file (tools/gen_ic_data.py writes one only when the data changed).
VERSIONS = ((5, 0), (5, 1), (5, 2))


def data_version(version=None):
    version = tuple(version or compat.VERSION)
    found = [v for v in VERSIONS if v <= version]
    return found[-1] if found else VERSIONS[0]


def generate():
    """Return a new list of IC keyconfig data (safe to mutate)."""
    v = data_version()
    data = copy.deepcopy(import_module(f".ic_{v[0]}_{v[1]}", __package__).DATA)
    if sys.platform == "darwin":
        from bl_keymap_utils.platform_helpers import keyconfig_data_oskey_from_ctrl_for_macos
        data = keyconfig_data_oskey_from_ctrl_for_macos(data)
    return data
