def _uv_plane():
    _clear()
    arm = _armature("skeleton1", [(0, 8, 0), (0, 4, 0), (0, 0, 0)], "joint")
    n = 6
    pts = [(x * 8 / n - 4, y * 8 / n, 0.0) for y in range(n + 1) for x in range(n + 1)]
    faces = [(y * (n + 1) + x, y * (n + 1) + x + 1, (y + 1) * (n + 1) + x + 1, (y + 1) * (n + 1) + x)
             for y in range(n) for x in range(n)]
    mesh = _mesh("pPlane1", pts, faces)
    uv = mesh.data.uv_layers.new(name="map1")
    for loop in mesh.data.loops:
        p = pts[loop.vertex_index]
        uv.data[loop.index].uv = (0.05 + 0.9 * (p[0] + 4) / 8, 0.05 + 0.9 * p[1] / 8)
    names, rows = skin.closest_distance_weights([Vector(p) for p in pts], skin.joint_segments(arm))
    _skin(mesh, arm, names, rows.tolist())
    _select(mesh)
    return arm, mesh, names, rows.tolist()


def test_weight_maps_round_trip_and_files():
    arm, mesh, names, rows = _uv_plane()
    folder = tempfile.mkdtemp(prefix="allset199_")
    path = os.path.join(folder, "skinMap.weightMap")
    r = bpy.ops.allset.export_weight_maps(filepath=path, size_x=256, size_y=256)
    assert r == {'FINISHED'}, r
    text = open(path, encoding="utf-8").read().splitlines()
    assert text[:2] == ["// Exported skin weight map file", "// "], text[:2]
    assert text[2:] == [f"pPlane1\t{n}\tpPlane1_{n}.png" for n in names], text
    for n in names:
        assert os.path.isfile(os.path.join(folder, "skinMap", f"pPlane1_{n}.png"))
    for vg in mesh.vertex_groups:                  # wreck the weights, then import them back
        vg.add(list(range(len(mesh.data.vertices))), 0.3, 'REPLACE')
    r = bpy.ops.allset.import_weight_maps(filepath=path)
    assert r == {'FINISHED'}, r
    got = _rows(mesh, names)
    d = _max_diff(got, rows)
    assert d < 4.0 / 255.0, f"round trip through 8-bit maps: {d}"
    for row in got:
        assert abs(sum(row) - 1.0) < 1e-6 or sum(row) == 0.0, "import normalises the weights"


