# --- Substitute Geometry -------------------------------------------------------------------------------------------
SUB_NAMES = ["joint1", "joint2", "joint3"]


def _sub_scene():
    _clear()
    arm = _armature("skeleton1", [(0, 8, 0), (0, 4, 0), (0, 0, 0)], "joint")
    old = _mesh("oldPlane", SUB_OLD_P, SUB_OLD_F)
    _skin(old, arm, SUB_NAMES, SUB_OLD_W)
    new = _mesh("newPlane", SUB_NEW_P, SUB_NEW_F)
    return arm, old, new


def test_substitute_geometry_matches_maya():
    arm, old, new = _sub_scene()
    for o in bpy.context.selected_objects:
        o.select_set(False)
    old.select_set(True)
    new.select_set(True)
    bpy.context.view_layer.objects.active = new
    r = bpy.ops.allset.substitute_geometry(reweight_distance=1.0)
    assert r == {'FINISHED'}, r
    assert "newPlane" not in bpy.data.objects and bpy.data.objects["oldPlane"] is old
    assert len(old.data.vertices) == len(SUB_NEW_P) and skin.armature_modifier(old).object == arm
    for v, p in zip(old.data.vertices, SUB_NEW_P):
        assert (v.co - Vector(p)).length < 1e-6
    got = _rows(old, SUB_NAMES)
    # Maya's closest-point weights: bilinear at the closest point; Maya's points are float32 (1.5e-5) and in the
    # outer quad columns Maya's closest point differs slightly (up to 9e-4)
    worst = max(abs(a - b) for ra, rb in zip(got, SUB_RES_W1) for a, b in zip(ra, rb))
    assert worst < 1e-3, worst
    inner = [i for i, p in enumerate(SUB_NEW_P) if abs(p[0]) < 3.0]
    worst_inner = max(abs(got[i][k] - SUB_RES_W1[i][k]) for i in inner for k in range(3))
    assert worst_inner < 5e-5, worst_inner
    # reweighting distance 0: every new vertex takes the nearest old vertex's weights (exact)
    arm, old, new = _sub_scene()
    st.substitute_geometry(bpy.context, old, new, 0.0)
    d = _max_diff(_rows(old, SUB_NAMES), SUB_RES_W0)
    assert d < TOL, f"wdt 0: {d}"


