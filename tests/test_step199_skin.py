# --- helpers ------------------------------------------------------------------------------------------------------

def _clear():
    if bpy.context.active_object is not None and bpy.context.mode != 'OBJECT':
        bpy.ops.object.mode_set(mode='OBJECT')
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob)
    for coll in (bpy.data.meshes, bpy.data.armatures, bpy.data.node_groups, bpy.data.images):
        for d in list(coll):
            coll.remove(d)
    us = bpy.context.scene.unit_settings
    us.system, us.length_unit, us.scale_length = 'METRIC', 'METERS', 1.0


def _armature(name, points, prefix):
    """Joint chain: bone k from joint k to joint k+1 (end joint: half the previous segment)."""
    data = bpy.data.armatures.new(name)
    ob = bpy.data.objects.new(name, data)
    bpy.context.scene.collection.objects.link(ob)
    bpy.context.view_layer.objects.active = ob
    bpy.ops.object.mode_set(mode='EDIT')
    prev = None
    for k, p in enumerate(points):
        eb = data.edit_bones.new(f"{prefix}{k + 1}")
        eb.head = p
        nxt = points[k + 1] if k + 1 < len(points) else None
        eb.tail = nxt if nxt is not None else Vector(p) + (Vector(p) - Vector(points[k - 1])) * 0.5
        if prev is not None:
            eb.parent = prev
            eb.use_connect = True
        prev = eb
    bpy.ops.object.mode_set(mode='OBJECT')
    return ob


def _mesh(name, points, faces=()):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(p) for p in points], [], [list(f) for f in faces])
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    return ob


def _skin(mesh, arm, names, rows, normalize="INTERACTIVE"):
    for name in names:
        mesh.vertex_groups.new(name=name)
    for vi, row in enumerate(rows):
        for name, w in zip(names, row):
            if w > 0.0:
                mesh.vertex_groups[name].add([vi], w, 'REPLACE')
    md = mesh.modifiers.new("skinCluster1", 'ARMATURE')
    md.object = arm
    mesh[skin.NORMALIZE_PROP] = normalize
    return mesh


def _rows(mesh, names):
    out = []
    for v in mesh.data.vertices:
        row = [0.0] * len(names)
        for g in v.groups:
            gname = mesh.vertex_groups[g.group].name
            if gname in names:
                row[names.index(gname)] = g.weight
        out.append(row)
    return out


def _max_diff(a, b):
    return max(abs(x - y) for ra, rb in zip(a, b) for x, y in zip(ra, rb))


def _select(ob, active=True):
    for o in bpy.context.selected_objects:
        o.select_set(False)
    ob.select_set(True)
    if active:
        bpy.context.view_layer.objects.active = ob


def _evaluated(ob):
    dg = bpy.context.evaluated_depsgraph_get()
    ev = ob.evaluated_get(dg)
    return [tuple(ev.matrix_world @ v.co) for v in ev.data.vertices]


