# --- Normalize Weights modes ---------------------------------------------------------------------------------------
NORM_NAMES = ["joint1", "joint2", "joint3"]


def _norm_scene(mode, offset=(0.0, 0.0, 0.0)):
    _clear()
    arm = _armature("skeleton1", [(0, 8, 0), (0, 4, 0), (0, 0, 0)], "joint")
    rows = globals()[f"NORM_W_{mode}"]
    mesh = _mesh("pCylinder1", [Vector(p) - Vector(offset) for p in CYL_REST])
    mesh.location = offset                        # world points like Maya's, object transform not frozen
    _skin(mesh, arm, NORM_NAMES, rows, "POST")
    _select(mesh)
    bpy.ops.allset.skin_normalize_mode(mode={0: "NONE", 1: "INTERACTIVE", 2: "POST"}[mode])
    # Maya pose: joint1 moved +1 X, joint2 turned 30 degrees about Z (world-aligned joints)
    s1 = Matrix.Translation((1, 0, 0))
    j2 = Vector((0, 4, 0))
    s2 = s1 @ Matrix.Translation(j2) @ Matrix.Rotation(math.radians(30), 4, 'Z') @ Matrix.Translation(-j2)
    for name, s in (("joint1", s1), ("joint2", s2), ("joint3", s2)):
        pb = arm.pose.bones[name]
        pb.matrix = s @ pb.bone.matrix_local
        bpy.context.view_layer.update()
    return arm, mesh


def test_normalize_modes_deform_like_maya():
    for mode in (0, 1, 2):
        for offset in ((0.0, 0.0, 0.0), (0.0, 4.0, 0.0)):
            arm, mesh = _norm_scene(mode, offset)
            got = _evaluated(mesh)
            want = globals()[f"NORM_POS_{mode}"]
            rows = globals()[f"NORM_W_{mode}"]
            # Blender clamps vertex group weights to [0, 1]: the expected 1.5 (vertex 12) can't be stored
            ok = [i for i, r in enumerate(rows) if max(r) <= 1.0]
            assert len(ok) == len(rows) - 1
            d = max((Vector(got[i]) - Vector(want[i])).length for i in ok)
            assert d < TOL, f"normalizeWeights {mode} offset {offset}: {d}"
            assert (st.sum_modifier(mesh) is None) == (mode == 2)
            assert skin.normalize_mode(mesh) == {0: "NONE", 1: "INTERACTIVE", 2: "POST"}[mode]


