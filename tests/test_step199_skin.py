def _move_scene(normalize="INTERACTIVE", lock=None, n_verts=22):
    _clear()
    arm = _armature("skeleton1", [(0, 8, 0), (0, 16 / 3, 0), (0, 8 / 3, 0), (0, 0, 0)], "joint")
    mesh = _mesh("pCylinder1", CYL_REST)
    _skin(mesh, arm, MOVE_NAMES, MOVE_BEFORE, normalize)
    if lock:
        mesh.vertex_groups[lock].lock_weight = True
    for v in mesh.data.vertices:
        v.select = v.index in MOVE_VERTS
    _select(mesh)
    return arm, mesh


