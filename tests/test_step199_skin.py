# --- Bake Deformation to Skin Weights ------------------------------------------------------------------------------
OFF = Vector((0.25, 0.3, 0.1))
CLUSTER = {12: 0.5, 13: 0.5, 14: 0.5, 15: 0.5, 16: 1.0, 17: 1.0, 18: 1.0, 19: 1.0, 21: 1.0}


def _bake_scene(src_rows, cluster):
    _clear()
    pts = [Vector((0, 8, 0)) + OFF, Vector((0, 4, 0)) + OFF, OFF.copy()]
    sarm = _armature("srcSkel", pts, "j")
    darm = _armature("dstSkel", pts, "j")
    src = _mesh("srcMesh", CYL_REST)
    _skin(src, sarm, ["j1", "j2", "j3"], src_rows)
    if cluster:                                   # Maya cluster (relative off) parented under joint2 = a Hook
        vg = src.vertex_groups.new(name="cluster1")
        for v, w in cluster.items():
            vg.add([v], w, 'REPLACE')
        handle = bpy.data.objects.new("cluster1Handle", None)
        bpy.context.scene.collection.objects.link(handle)
        handle.parent = sarm
        handle.parent_type = 'BONE'
        handle.parent_bone = "j2"
        bpy.context.view_layer.update()
        handle.matrix_world = Matrix.Identity(4)
        bpy.context.view_layer.update()
        hook = src.modifiers.new("cluster1", 'HOOK')
        hook.object = handle
        hook.vertex_group = "cluster1"
        hook.falloff_type = 'NONE'
        hook.matrix_inverse = handle.matrix_world.inverted() @ src.matrix_world
    dst = _mesh("dstMesh", CYL_REST)
    _skin(dst, darm, ["j1", "j2", "j3"], [[1.0, 0.0, 0.0]] * len(CYL_REST))
    for o in bpy.context.selected_objects:
        o.select_set(False)
    src.select_set(True)
    dst.select_set(True)
    bpy.context.view_layer.objects.active = dst
    return src, dst


def test_bake_deformation_recovers_a_skin_like_maya():
    src, dst = _bake_scene(BAKE_UNEVEN_W, None)
    r = bpy.ops.allset.bake_deformation(max_influences=3)
    assert r == {'FINISHED'}, r
    d = _max_diff(_rows(dst, ["j1", "j2", "j3"]), BAKE_UNEVEN_AFTER)
    assert d < TOL, f"pure skin source: {d}"


def test_bake_deformation_with_a_deformer_matches_maya():
    src, dst = _bake_scene(BAKE_SRC_W, CLUSTER)
    bpy.ops.allset.bake_deformation(max_influences=3)
    got = _rows(dst, ["j1", "j2", "j3"])
    # vertices 12-15 have cluster weight 0.5: Maya's bake gives them about the result of
    # weight 1 (j2 0.999), the kit fits their real deformation (j1 0.43 / j2 0.57) -
    full = [i for i in range(len(got)) if i not in (12, 13, 14, 15)]
    d = max(abs(got[i][k] - BAKE_AFTER[i][k]) for i in full for k in range(3))
    assert d < TOL, f"skin + cluster source: {d}\n{got}"
    for i in (12, 13, 14, 15):
        assert abs(sum(got[i]) - 1.0) < 1e-6 and got[i][1] > 0.5
    for pb in bpy.data.objects["srcSkel"].pose.bones:
        assert pb.matrix_basis == Matrix.Identity(4), "the sampling must put the pose back"


